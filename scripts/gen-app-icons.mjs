#!/usr/bin/env node
// Static brand assets are generated here; consumers copy the emitted SVG bytes.
import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const args = process.argv.slice(2)
const check = args.includes('--check')
const source = await readFile(resolve(root, 'brand/app-icons.json'), 'utf8')
const family = JSON.parse(source)
const css = await readFile(resolve(root, 'src/index.css'), 'utf8')
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex')
const token = (block, name) => {
  const value = block.match(new RegExp(`--${name}:\\s*(#[0-9a-fA-F]{6})\\s*;`))?.[1]
  if (!value) throw new Error(`Missing ${name} token`)
  return value
}
const darkBlock = css.match(/^:root\s*\{([^}]+)\}/m)?.[1] ?? ''
const lightBlock = css.match(/^\[data-theme="light"\]\s*\{([^}]+)\}/m)?.[1] ?? ''
const colors = Object.fromEntries([['dark', darkBlock], ['light', lightBlock]].map(([theme, block]) => [theme, {
  canvas: token(block, 'canvas'), amber: token(block, 'amber'),
}]))

function render(app, theme = null) {
  const pairs = family.variants[app]
  if (!pairs) throw new Error(`Unknown app icon: ${app}`)
  const paths = [family.stem, ...family.branchPairs.slice(0, pairs).flat()]
  const palette = colors[theme ?? 'dark']
  const light = theme ? '' : `@media(prefers-color-scheme:light){:root{--canvas:${colors.light.canvas};--amber:${colors.light.amber}}}`
  return `<!-- Generated by fairtrade scripts/gen-app-icons.mjs; ${app}; source sha256 ${family.source.sha256}. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32">
  <style>:root{--canvas:${palette.canvas};--amber:${palette.amber}}${light}</style>
  <rect width="32" height="32" fill="var(--canvas)"/>
  <g transform="translate(5 3) scale(1.2222)" fill="none" stroke="var(--amber)" stroke-width="${family.strokeWidth}" stroke-linecap="${family.strokeLinecap}">
${paths.map((d) => `    <path d="${d}"/>`).join('\n')}
  </g>
</svg>
`
}

const outputs = new Map(Object.keys(family.variants).map((app) => [`public/brand/${app}.svg`, Buffer.from(render(app))]))
outputs.set('public/favicon.svg', outputs.get('public/brand/fairtrade.svg'))

// Optional local verification has no dependency on another checkout in CI.
const headerIndex = args.indexOf('--header')
if (headerIndex !== -1) {
  const header = await readFile(resolve(args[headerIndex + 1]), 'utf8')
  const paths = [...header.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1])
  const expected = [family.stem, ...family.branchPairs.slice(0, family.variants.website).flat()]
  if (JSON.stringify(paths) !== JSON.stringify(expected)
    || !header.includes(`viewBox="${family.viewBox}"`)
    || !header.includes(`strokeWidth={${family.strokeWidth}}`)
    || !header.includes(`strokeLinecap="${family.strokeLinecap}"`)) throw new Error('Landing-page header geometry differs from the icon family source')
}
for (let i = 0; i < args.length; i++) {
  if (args[i] !== '--copy-check') continue
  const app = args[++i]
  const path = args[++i]
  if (!path || !outputs.has(`public/brand/${app}.svg`)) throw new Error('Usage: --copy-check <app> <icon.svg>')
  if (!(await readFile(resolve(path))).equals(outputs.get(`public/brand/${app}.svg`))) throw new Error(`Stale ${app} icon: ${path}`)
}

if (!check) {
  await mkdir(resolve(root, 'public/brand'), { recursive: true })
  for (const [path, bytes] of outputs) await writeFile(resolve(root, path), bytes)
  // Rasterize the same Fairtrade SVG, using the dark token palette for Apple launchers.
  const { chromium } = await import('@playwright/test')
  const browser = await chromium.launch()
  try {
    const page = await browser.newPage({ viewport: { width: 180, height: 180 }, deviceScaleFactor: 1, colorScheme: 'dark' })
    await page.setContent(`<style>html,body{margin:0}svg{display:block;width:180px;height:180px}</style>${render('fairtrade', 'dark')}`)
    await page.screenshot({ path: resolve(root, 'public/apple-touch-icon.png') })
  } finally {
    await browser.close()
  }
}
for (const [path, expected] of outputs) {
  if (!(await readFile(resolve(root, path))).equals(expected)) throw new Error(`Stale generated icon: ${path}; run node scripts/gen-app-icons.mjs`)
}
const png = await readFile(resolve(root, 'public/apple-touch-icon.png'))
if (png.toString('hex', 0, 8) !== '89504e470d0a1a0a' || png.readUInt32BE(16) !== 180 || png.readUInt32BE(20) !== 180) throw new Error('Apple icon must be a 180x180 PNG')
outputs.set('public/apple-touch-icon.png', png)
const manifest = JSON.stringify({ source: family.source, familySha256: digest(source), colors,
  assets: Object.fromEntries([...outputs].map(([path, bytes]) => [path, digest(bytes)])),
}, null, 2) + '\n'
const manifestPath = resolve(root, 'public/brand/provenance.json')
if (check) {
  if (await readFile(manifestPath, 'utf8') !== manifest) throw new Error('Icon provenance differs; regenerate the family')
} else {
  await writeFile(manifestPath, manifest)
}
console.log(`app icons ${check ? 'verified' : 'generated'}: ${Object.keys(family.variants).join(', ')}`)
